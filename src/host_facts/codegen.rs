macro_rules! list_helper {
    () => {
        "    /** @return list<string> */\n    private static function listOfString(mixed $value, string $path): array\n    {\n        if (!is_array($value) || array_is_list($value) === false) {\n            throw new InvalidArgumentException(\"{$path} must be list<string>.\");\n        }\n\n        foreach ($value as $item) {\n            if (!is_string($item)) {\n                throw new InvalidArgumentException(\"{$path} must be list<string>.\");\n            }\n        }\n\n        return $value;\n    }\n\n"
    };
}

macro_rules! shape_helper {
    () => {
        "    /** @param array<string, mixed> $data @param list<string> $keys */\n    private static function assertShape(array $data, array $keys, string $type): void\n    {\n        $actual = array_keys($data);\n        $missing = array_values(array_diff($keys, $actual));\n        $unknown = array_values(array_diff($actual, $keys));\n\n        if ($missing !== []) {\n            throw new InvalidArgumentException($type . ' missing keys: ' . implode(', ', $missing));\n        }\n\n        if ($unknown !== []) {\n            throw new InvalidArgumentException($type . ' unknown keys: ' . implode(', ', $unknown));\n        }\n    }\n\n"
    };
}


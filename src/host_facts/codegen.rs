pub fn write_to(root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let target = root.join(TARGET_DIR);

    std::fs::create_dir_all(&target)?;

    for file in generated_files() {
        std::fs::write(target.join(file.path), file.contents)?;
    }

    Ok(())
}

pub fn check_fresh(root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let target = root.join(TARGET_DIR);
    let mut stale = Vec::new();

    for file in generated_files() {
        let path = target.join(file.path);
        match std::fs::read_to_string(&path) {
            Ok(existing) if existing == file.contents => {}
            Ok(_) => stale.push(file.path.to_string()),
            Err(_) => stale.push(file.path.to_string()),
        }
    }

    if stale.is_empty() {
        return Ok(());
    }

    Err(format!(
        "host facts generated files are stale or missing: {} (run cargo xtask gen-host-facts)",
        stale.join(", ")
    )
    .into())
}

